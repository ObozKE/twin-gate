-- Target Engine: PostgreSQL 16
-- ==============================================================================

-- Create application schema if not exists
CREATE TABLE IF NOT EXISTS transactions (
    id BIGSERIAL PRIMARY KEY,
    idempotency_key UUID NOT NULL UNIQUE,
    account_id VARCHAR(64) NOT NULL,
    amount NUMERIC(15, 2) NOT NULL CHECK (amount > 0),
    currency VARCHAR(3) NOT NULL DEFAULT 'KES',
    tx_type VARCHAR(16) NOT NULL CHECK (tx_type IN ('DEBIT', 'CREDIT', 'TRANSFER')),
    status VARCHAR(16) NOT NULL DEFAULT 'COMMITTED',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    backend_node VARCHAR(64) NOT NULL
);

-- Index for temporal queries and auditing
CREATE INDEX IF NOT EXISTS idx_transactions_created_at ON transactions (created_at);
CREATE INDEX IF NOT EXISTS idx_transactions_account_id ON transactions (account_id);

-- Display table verification metadata
COMMENT ON TABLE transactions IS 'Carrier-grade financial transactions with strictly enforced UUID idempotency.';
COMMENT ON COLUMN transactions.idempotency_key IS 'UUIDv4 key generated by client; enforces exactly-once transaction semantics.';
